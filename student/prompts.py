def _format_hits(hits) -> str:
    limit = max(0, int(getattr(settings, "MAX_CONTEXT_CHARS", 6000)))
    blocks: list[str] = []
    used = 0
    for index, hit in enumerate(hits or [], 1):
        try:
            chunk, score = hit
            doc_id, text = str(chunk.doc_id), str(chunk.text)
        except (TypeError, AttributeError, ValueError):
            continue
        block = f"[แหล่งที่ {index}: {doc_id}, score={score:.3f}]\n{text.strip()}"
        remaining = limit - used
        if remaining <= 0:
            break
        if len(block) > remaining:
            block = block[:remaining]
        if block.strip():
            blocks.append(block)
            used += len(block)
    return "\n\n---\n\n".join(blocks)
