def build_mc_prompt(question: str, options: list[tuple[str, str]], hits) -> list[dict]:
    """prompt สำหรับข้อสอบปรนัย

    รับ:  question  คำถาม
          options   list ของ (key, text) เช่น [("ก", "O(1)"), ("ข", "O(log n)"), ...]
          hits      chunk ที่ค้นได้ (list ของ (chunk, score)) อาจเป็น list ว่าง
    คืน:  list ของ message

    หมายเหตุ: core บังคับให้ LLM ตอบเป็น JSON {"reason": "...", "answer": "<key>"} ให้อยู่แล้ว
    แนวทาง:
      - ใส่เนื้อหาของ hits เป็น "เอกสารอ้างอิง" แล้วสั่งให้ยึดเอกสารเป็นหลัก แม้จะขัดกับความรู้ทั่วไป
      - แสดงตัวเลือกพร้อม key (ก. ... ข. ...)
      - ระวังคำถามเชิงปฏิเสธ เช่น "ข้อใด**ไม่**ถูกต้อง"
    """
    choices = "\n".join(f"{key}. {text}" for key, text in options)
    context = _format_hits(hits)
    return [
        {"role": "system", "content": (
            "คุณเป็นผู้ช่วยตอบข้อสอบแบบปรนัยภาษาไทย ใช้เอกสารอ้างอิงที่ให้มาเป็นหลัก "
            "แม้ข้อมูลในเอกสารจะต่างจากความรู้ทั่วไปก็ตาม อ่านคำปฏิเสธ เช่น ไม่, ยกเว้น, ผิด ให้รอบคอบ "
            "หาประโยคในเอกสารที่ตอบสถานการณ์เฉพาะของคำถาม แล้วเทียบความหมายกับตัวเลือกทีละข้อ "
            "อย่าสับสนระหว่างรูปแบบข้อมูลกับวิธีที่ระบบแปลงหรือประมวลผลข้อมูล "
            "เลือก key ที่สอดคล้องกับเอกสารเพียงหนึ่งตัว ห้ามสร้างตัวเลือกใหม่ "
            "หากเอกสารไม่พอ ให้ใช้ความรู้ที่เชื่อถือได้และระบุข้อจำกัดใน reason "
            "ตอบเป็น JSON ตาม schema ที่ระบบกำหนดเท่านั้น"
        )},
        {"role": "user", "content": f"เอกสารอ้างอิง:\n{context or '(ไม่มีเอกสารที่ค้นพบ)'}\n\nคำถาม:\n{question}\n\nตัวเลือก:\n{choices}"},
    ]


